export function searchVillages(query: string): Array<{
  village: string;
  unionName: string;
  upazilaName: string;
  upazilaId: string;
  postCode: string;
  lat: number;
  lng: number;
}> {
  if (!query || query.trim().length === 0) return [];
  const q = query.trim().toLowerCase();
  const results: Array<{
    village: string;
    unionName: string;
    upazilaName: string;
    upazilaId: string;
    postCode: string;
    lat: number;
    lng: number;
  }> = [];

  for (const u of boguraUpazilasData) {
    for (const un of u.unions) {
      for (const v of un.villages) {
        if (v.toLowerCase().includes(q)) {
          results.push({
            village: v,
            unionName: un.name,
            upazilaName: u.name,
            upazilaId: u.id,
            postCode: un.postCode,
            lat: un.lat,
            lng: un.lng
          });
        }
      }
    }
  }
  return results.slice(0, 50);
}

